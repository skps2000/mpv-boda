local function table_for()
    local lang = tostring(opts.language or "en"):lower()
    return S[lang] or S.en
end

-- t("key") or t("key", arg1, ...) when the string has format placeholders
function M.t(key, ...)
    local tbl = table_for()
    local s = tbl[key] or S.en[key] or key
    if select("#", ...) > 0 then
        local ok, out = pcall(string.format, s, ...)
        if ok then return out end
    end
    return s
end

function M.languages()
    local out = {}
    for name in pairs(S) do out[#out + 1] = name end
    table.sort(out)
    return out
end

return M
